import AppKit
import Foundation

public struct ClipboardHistoryEntry: Identifiable, Codable, Equatable, Sendable {
    public let id: UUID
    public let content: String
    public let copiedAt: Date
    public let sourceApp: String?

    public var previewLine: String {
        content
            .replacingOccurrences(of: "\\s+", with: " ", options: .regularExpression)
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }

    public var characterCount: Int {
        content.count
    }

    public init(
        id: UUID = UUID(),
        content: String,
        copiedAt: Date = .now,
        sourceApp: String? = nil
    ) {
        self.id = id
        self.content = content
        self.copiedAt = copiedAt
        self.sourceApp = sourceApp
    }
}

/// Pairs a cached clipboard entry with its 1-based position (`1...50`) in the full MRU ring
/// so filtered search results still display each item's original stack slot (e.g. `#50`).
public struct IndexedClipboardEntry: Identifiable, Equatable, Sendable {
    public let entry: ClipboardHistoryEntry
    public let originalRank: Int

    public var id: UUID { entry.id }

    public init(entry: ClipboardHistoryEntry, originalRank: Int) {
        self.entry = entry
        self.originalRank = originalRank
    }
}

/// Background macOS clipboard history ring storing up to 50 direct clipboard copies.
/// - Polls `NSPasteboard.general.changeCount` on a lightweight 400ms timer (macOS has no pasteboard push API).
/// - Strictly skips concealed/transient/auto-generated items (1Password, Keychain, SnipBar secrets, and SnipBar snippets).
/// - Deduplicates repeated copies by promoting the existing entry to index 0.
/// - Persists inside `~/Library/Application Support/SnipBar/clipboard-history.json` (`0700` directory).
@MainActor
public final class ClipboardHistoryStore: ObservableObject {
    public static let shared = ClipboardHistoryStore()
    public nonisolated static let hardMaxEntries = 50

    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let onePasswordType = NSPasteboard.PasteboardType("com.agilebits.onepassword")

    private static let enabledKey = "snipbar.clipboardHistoryEnabled"
    private static let maxEntriesKey = "snipbar.clipboardHistoryMaxEntries"
    private static let pasteOnReleaseKey = "snipbar.clipboardPasteOnRelease"

    @Published public private(set) var entries: [ClipboardHistoryEntry] = []

    @Published public var isEnabled: Bool {
        didSet {
            defaults.set(isEnabled, forKey: Self.enabledKey)
            if isEnabled {
                startMonitoring()
            } else {
                stopMonitoring()
            }
        }
    }

    @Published public var maxEntries: Int {
        didSet {
            let clamped = max(5, min(Self.hardMaxEntries, maxEntries))
            if clamped != maxEntries {
                maxEntries = clamped
                return
            }
            defaults.set(clamped, forKey: Self.maxEntriesKey)
            trimToLimit()
            persistIfNeeded()
        }
    }

    @Published public var pasteOnReleaseCommand: Bool {
        didSet {
            defaults.set(pasteOnReleaseCommand, forKey: Self.pasteOnReleaseKey)
        }
    }

    private let storageURL: URL?
    private let defaults: UserDefaults
    private var pollTask: Task<Void, Never>?
    private var lastObservedChangeCount: Int
    private var ignoredChangeCounts: Set<Int> = []

    public init(
        storageURL: URL? = ClipboardHistoryStore.defaultStorageURL(),
        userDefaultsSuiteName: String? = nil
    ) {
        self.storageURL = storageURL
        let resolvedDefaults = userDefaultsSuiteName.flatMap { UserDefaults(suiteName: $0) } ?? .standard
        self.defaults = resolvedDefaults

        if resolvedDefaults.object(forKey: Self.enabledKey) == nil {
            self.isEnabled = true
        } else {
            self.isEnabled = resolvedDefaults.bool(forKey: Self.enabledKey)
        }

        let storedMax = resolvedDefaults.integer(forKey: Self.maxEntriesKey)
        self.maxEntries = storedMax > 0
            ? max(5, min(Self.hardMaxEntries, storedMax))
            : Self.hardMaxEntries

        if resolvedDefaults.object(forKey: Self.pasteOnReleaseKey) == nil {
            self.pasteOnReleaseCommand = true
        } else {
            self.pasteOnReleaseCommand = resolvedDefaults.bool(forKey: Self.pasteOnReleaseKey)
        }

        self.lastObservedChangeCount = NSPasteboard.general.changeCount
        loadFromDisk()
    }

    /// Tells the clipboard monitor to skip a pasteboard write initiated by SnipBar itself
    /// (e.g., copying an explicit snippet or re-pasting a clipboard history entry).
    public func ignoreChangeCount(_ changeCount: Int) {
        ignoredChangeCounts.insert(changeCount)
        if ignoredChangeCounts.count > 12 {
            ignoredChangeCounts = [changeCount]
        }
    }

    public func startMonitoring() {
        guard isEnabled, pollTask == nil else { return }
        lastObservedChangeCount = NSPasteboard.general.changeCount

        pollTask = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: .milliseconds(400))
                guard !Task.isCancelled else { break }
                self?.pollPasteboardOnce()
            }
        }
    }

    public func stopMonitoring() {
        pollTask?.cancel()
        pollTask = nil
    }

    /// Records a plain-text clipboard entry (deduplicated, newest-first, capped at `maxEntries` <= 50).
    @discardableResult
    public func record(content: String, sourceApp: String? = nil, copiedAt: Date = .now) -> ClipboardHistoryEntry? {
        let trimmed = content.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }

        // Deduplicate by exact text, lifting most recent copy to index 0
        entries.removeAll { $0.content == content }

        let entry = ClipboardHistoryEntry(
            content: content,
            copiedAt: copiedAt,
            sourceApp: sourceApp
        )
        entries.insert(entry, at: 0)
        trimToLimit()
        persistIfNeeded()
        return entry
    }

    public func remove(id: UUID) {
        entries.removeAll { $0.id == id }
        persistIfNeeded()
    }

    public func clearAll() {
        entries.removeAll()
        persistIfNeeded()
    }

    /// Moves a chosen entry to the top after direct pasting (keeps the clipboard stack MRU-ordered).
    public func promoteToTop(id: UUID) {
        guard let idx = entries.firstIndex(where: { $0.id == id }), idx > 0 else { return }
        let item = entries.remove(at: idx)
        entries.insert(item, at: 0)
        persistIfNeeded()
    }

    private func pollPasteboardOnce() {
        guard isEnabled else { return }
        let pasteboard = NSPasteboard.general
        let currentCount = pasteboard.changeCount
        guard currentCount != lastObservedChangeCount else { return }
        lastObservedChangeCount = currentCount

        if ignoredChangeCounts.remove(currentCount) != nil {
            return
        }

        // Never capture concealed/transient secrets from password managers or SnipBar itself
        let types = Set(pasteboard.types ?? [])
        if types.contains(Self.concealedType)
            || types.contains(Self.transientType)
            || types.contains(Self.autoGeneratedType)
            || types.contains(Self.onePasswordType) {
            return
        }

        guard let text = pasteboard.string(forType: .string) else { return }
        let frontApp = NSWorkspace.shared.frontmostApplication?.localizedName
        _ = record(content: text, sourceApp: frontApp)
    }

    private func trimToLimit() {
        let cap = min(Self.hardMaxEntries, maxEntries)
        if entries.count > cap {
            entries = Array(entries.prefix(cap))
        }
    }

    private func loadFromDisk() {
        guard let storageURL,
              let data = try? Data(contentsOf: storageURL),
              let decoded = try? JSONDecoder().decode([ClipboardHistoryEntry].self, from: data) else {
            return
        }
        entries = Array(decoded.prefix(min(Self.hardMaxEntries, maxEntries)))
    }

    private func persistIfNeeded() {
        guard let storageURL else { return }
        let dir = storageURL.deletingLastPathComponent()
        try? FileManager.default.createDirectory(
            at: dir,
            withIntermediateDirectories: true,
            attributes: [.posixPermissions: 0o700]
        )
        if let data = try? JSONEncoder().encode(entries) {
            try? data.write(to: storageURL, options: [.atomic])
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: storageURL.path)
        }
    }

    public nonisolated static func defaultStorageURL() -> URL? {
        FileManager.default
            .urls(for: .applicationSupportDirectory, in: .userDomainMask)
            .first?
            .appendingPathComponent("SnipBar", isDirectory: true)
            .appendingPathComponent("clipboard-history.json")
    }

    /// Filters cached clipboard entries by a search query while preserving each item's
    /// 1-based position (`1...50`) in the full clipboard stack.
    /// Matches multi-word queries across clipping content, source app name, or `#rank` (e.g. `#50`).
    public nonisolated static func filterEntries(
        _ entries: [ClipboardHistoryEntry],
        query: String
    ) -> [IndexedClipboardEntry] {
        let trimmed = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else {
            return entries.enumerated().map { idx, entry in
                IndexedClipboardEntry(entry: entry, originalRank: idx + 1)
            }
        }

        let tokens = trimmed
            .split(whereSeparator: \.isWhitespace)
            .map { String($0).lowercased() }

        var scored: [(item: IndexedClipboardEntry, exactHits: Int)] = []
        scored.reserveCapacity(entries.count)

        for (idx, entry) in entries.enumerated() {
            let rank = idx + 1
            let rankLabel = "#\(rank)"
            let contentLower = entry.content.lowercased()
            let appLower = (entry.sourceApp ?? "").lowercased()

            var exactHits = 0
            var matchedAll = true

            for token in tokens {
                if token.hasPrefix("#") && token.count > 1 {
                    if rankLabel == token || rankLabel.hasPrefix(token) {
                        exactHits += 2
                        continue
                    }
                }

                if contentLower.contains(token) {
                    exactHits += 2
                } else if !appLower.isEmpty && appLower.contains(token) {
                    exactHits += 1
                } else if token.count >= 2 && isSubsequence(needle: token, haystack: contentLower) {
                    // Fuzzy subsequence match fallback (ranked below exact substring hits)
                    continue
                } else {
                    matchedAll = false
                    break
                }
            }

            if matchedAll {
                scored.append((IndexedClipboardEntry(entry: entry, originalRank: rank), exactHits))
            }
        }

        scored.sort { lhs, rhs in
            if lhs.exactHits != rhs.exactHits {
                return lhs.exactHits > rhs.exactHits
            }
            return lhs.item.originalRank < rhs.item.originalRank
        }

        return scored.map(\.item)
    }

    private nonisolated static func isSubsequence(needle: String, haystack: String) -> Bool {
        var needleIndex = needle.startIndex
        for ch in haystack where needleIndex < needle.endIndex {
            if ch == needle[needleIndex] {
                needleIndex = needle.index(after: needleIndex)
            }
        }
        return needleIndex == needle.endIndex
    }
}
