import AppKit
import Foundation

/// Hardened macOS pasteboard manager solving three critical menu-bar caveats:
/// 1. Blocks Universal Clipboard / Handoff wireless sync for secrets via `.currentHostOnly`.
/// 2. Marks secrets with `org.nspasteboard.ConcealedType` & `TransientType` so 3rd-party
///    clipboard history managers (Raycast, Paste, Maccy, Alfred, 1Password) ignore them.
/// 3. Tracks `NSPasteboard.general.changeCount` before scheduling auto-clear so we NEVER
///    accidentally wipe something else the user copied after our snippet.
@MainActor
public final class ClipboardService: ObservableObject {
    public static let shared = ClipboardService()

    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    @Published public private(set) var pendingAutoClearChangeCount: Int?
    private var autoClearTask: Task<Void, Never>?

    private init() {}

    /// Writes text to `NSPasteboard.general` with appropriate privacy markers and optional auto-clear.
    /// - When `skipHistoryCapture == false` and `!isSecret`, the copied text is also recorded
    ///   immediately at slot `#1` of SnipBar's 50-entry `ClipboardHistoryStore` (while still
    ///   suppressing duplicate capture from the 400ms pasteboard poller).
    /// - Masked secrets (`isSecret == true`) are never stored in plaintext clipboard history.
    @discardableResult
    public func copy(
        _ text: String,
        isSecret: Bool = false,
        isTransient: Bool = false,
        autoClearAfterSeconds: Int? = nil,
        skipHistoryCapture: Bool = true,
        historySourceApp: String? = "SnipBar"
    ) -> Int {
        autoClearTask?.cancel()
        autoClearTask = nil
        pendingAutoClearChangeCount = nil

        let pasteboard = NSPasteboard.general

        // Block Handoff / Universal Clipboard broadcast to nearby iPhones/iPads for secrets
        if isSecret {
            _ = pasteboard.prepareForNewContents(with: .currentHostOnly)
        } else {
            pasteboard.clearContents()
        }

        pasteboard.setString(text, forType: .string)

        if isSecret {
            pasteboard.setData(Data(), forType: Self.concealedType)
            pasteboard.setData(Data(), forType: Self.autoGeneratedType)
        }

        if isTransient {
            pasteboard.setData(Data(), forType: Self.transientType)
            pasteboard.setData(Data(), forType: Self.autoGeneratedType)
        }

        let recordedCount = pasteboard.changeCount

        // Prevent the 400ms background pasteboard poller from duplicating or misattributing this write
        ClipboardHistoryStore.shared.ignoreChangeCount(recordedCount)

        // Immediately add non-secret copied snippets into SnipBar's 50-entry clipboard stack
        if !skipHistoryCapture && !isSecret && ClipboardHistoryStore.shared.isEnabled {
            _ = ClipboardHistoryStore.shared.record(
                content: text,
                sourceApp: historySourceApp
            )
        }

        if let seconds = autoClearAfterSeconds, seconds > 0 {
            pendingAutoClearChangeCount = recordedCount
            autoClearTask = Task { [weak self] in
                try? await Task.sleep(for: .seconds(seconds))
                guard !Task.isCancelled else { return }
                self?.clearIfUnchanged(expectedChangeCount: recordedCount)
            }
        }

        return recordedCount
    }

    /// Reads current plain-text clipboard safely for `{{clipboard}}` variable or `+ From Clipboard`.
    public func readPlainText() -> String? {
        let pasteboard = NSPasteboard.general
        // Respect concealed items already on the clipboard—never ingest another app's secret!
        if pasteboard.types?.contains(Self.concealedType) == true {
            return nil
        }
        return pasteboard.string(forType: .string)
    }

    private func clearIfUnchanged(expectedChangeCount: Int) {
        let pasteboard = NSPasteboard.general
        defer {
            if pendingAutoClearChangeCount == expectedChangeCount {
                pendingAutoClearChangeCount = nil
            }
        }
        // Only clear if nothing else was copied since our write
        guard pasteboard.changeCount == expectedChangeCount else { return }
        pasteboard.clearContents()
    }
}
